#!/usr/bin/env python3
"""语义自查提醒器（2026-08-31 审查补齐 C2）。

输出单章生成后必须人工复核的语义检查清单。机械审计（字数/纯净/结构/标题）
请用 audit_chapter.py——脚本管机器能管的部分，本脚本管必须人眼判断的部分。

用法:
    python3 scripts/semantic_reminder.py --chapter 3
    python3 scripts/semantic_reminder.py --chapter 3 --opening   # 含开篇锁位表
"""
from __future__ import annotations

import argparse

GROUPS: list[tuple[str, list[str]]] = [
    ("灵魂三问（生成前应已写入章卡，复核答案）", [
        "本章读者会不会爽到/揪心到/燃到（至少一种，最好两种）？",
        "章末不点下一章，读者会不会难受？",
        "本章信息与情绪能否支撑下一个 500 字继续读？",
    ]),
    ("逐章语义检查（每章必查，引用正文位置）", [
        "本章是否有 ≥1 个落袋微爽点（可感知结果：见血/碎物/跪地/变色/惊呼）？",
        "章末最后 3 句是否动作压力 + 改写因果的新信息双钩子？",
        "主角是否有 ≥1 个可感知情绪支点（身体反应/内心一句/决定性动作）？",
        "本章是否 ≥3 种情绪且有落差？暖的情绪是否出现？",
        "每 500 字是否有抓人点？有无连续 300 字以上纯描写？",
        "每 300 字是否情绪↔信息交替？有无连续 500 字单边？",
        "环境描写是否 ≤15% 且每处有功能（危险/情绪/线索/对比）？",
        "对话是否 ≥四成、有刀（信息差/压迫）、每段 ≤3 句？",
        "本章爽点是否与近 3 章不同型？同型是否已升级对象/规模/方式？",
        "主线谜团本章是否推进一步？次要悬念是否动了一个？",
    ]),
    ("留存 36 锁抽查（对应章节触发时）", [
        "留01 爽感循环五环是否完整（触发→代价→使用→战果放大→认知升级）？",
        "留08 打脸是否三层递进（破防→碾压→定性）且有余韵？",
        "留11 代价与收益是否同章兑换且读者觉得值？",
        "留15 金手指视觉意象与状态颜色是否一致？",
        "留17/留04 开篇与章末是否达标（第 1 章/每章）？",
        "留22 收集进度条是否在获得后更新？",
        "留26 章末 200 字是否'不忍心放下'型悬念？",
        "留33 用能力后是否留了欠债意识？",
    ]),
    ("衬检 1–8（本章含反衬场景时逐项）", [
        "主次分明（主角唯一焦点，陪衬不喧宾夺主）？",
        "落差足够（陪衬之弱/狂与主角之强/淡都写到）？",
        "铺垫合理（强有伏笔、狂有依据）？",
        "情绪积累充分？爆发利落？余波渲染到位？",
        "反衬维度与近 3 章不重复？有信息增量？",
    ]),
    ("双/怀合同（含 NPD 或族群桥段时）", [
        "双标是否可视化到'读者能立刻指出不公平'？",
        "群体是否有反转（指责→声讨 NPD）？",
        "逻辑反杀是否一句 ≤20 字且 200 字内有动作/物证兑现？",
        "NPD 失态是否符合性格（外强中干）？清算是否彻底？",
        "民族/族群桥段是否已架空化（无现实国家/民族/纪年）？",
        "NPD 压抑是否未豁免本章微爽点/小温暖？",
    ]),
    ("对齐协议 16 问（前三章逐章）", [
        "删掉金手指，本章结局会变吗？",
        "四拍是否齐（获得/使用/代价/偿还或违约）？",
        "代价是否在围观反应之后（先满后亏）？",
        "开篇反派还握着哪项资源？",
        "前 300 字有数字死线吗？越级胜前有标尺句吗？",
        "过账/传话/物件三通道满 2 条吗？意象是否超 1-1-1 预算？",
        "本章核心动作是一个还是一串？章末是情节还是灯花？",
    ]),
    ("滚动窗口（跨章登记，未到期写'尚未到期，已规划'）", [
        "每 3 章：第四方案 ≥1？主爽点 ≥1？小反转 ≥1？爽/虐/燃三类各 ≥1？",
        "每 5 章：降维打击 ≥1？战力三层楼已亮出？",
        "每 10 章：名场面 ≥1？",
        "连续性：时间账连续？伏笔悬挂 ≤30 章？人设无 OOC？经济账平衡？",
        "章尾安全区三禁令（安全区+威胁降级+困境闭环不得同时成立）？",
    ]),
]


def main() -> int:
    parser = argparse.ArgumentParser(description="输出单章语义自查清单（人工复核用）")
    parser.add_argument("--chapter", type=int, default=0, help="章节号，用于标注滚动窗口到期项")
    parser.add_argument("--opening", action="store_true", help="追加开篇 0-1000 字锁位排布表提醒（第 1-3 章建议开启）")
    args = parser.parse_args()

    ch = f"第 {args.chapter} 章" if args.chapter else "本章"
    print(f"[语义自查提醒] {ch} —— 以下各项需人工复核并引用正文位置，结论写 QA 侧车：")
    print("（机械项——字数/纯净/结构/标题——请另跑 audit_chapter.py）")
    for title, items in GROUPS:
        print(f"\n## {title}")
        for i, item in enumerate(items, 1):
            print(f"  [ ] {i}. {item}")
    if args.opening:
        print("\n## 开篇锁位排布表（详见 references/opening-locks-map.md）")
        for line in [
            "第 1 句：冲突首句（禁天气/起床/说明书）",
            "0-100 净字：留17 异常 + 身体信号",
            "0-150 净字：HOOK-EMO-01 三类元素，锚点值≥6",
            "0-300 含标点：留存锁1 目标/时限/永久后果",
            "0-300：对05 黄金三段（预热≠超凡动作）",
            "≤200/≤500 含标点：B12 欺压落地 / 生存面子危机",
            "第 4 段起：首次超凡动作（晚于第 3 段）+ 双代价",
            "0-1000 净字：4.1 命运危机（预期落空+利益或危机）",
        ]:
            print(f"  [ ] {line}")
    print("\n任一 FAIL：只回滚其触发范围，重新生成并复检；结论严禁写入小说正文。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
